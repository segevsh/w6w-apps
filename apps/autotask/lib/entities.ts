const BY_LOWER = new Map(ENTITIES.map((e) => [e.toLowerCase(), e]));

/** Resolve a caller's spelling to the canonical entity name, or undefined if it is not queryable. */
export function canonicalEntity(value: unknown): string | undefined {
  return BY_LOWER.get(String(value ?? "").trim().toLowerCase());
}
