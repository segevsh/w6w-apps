#!/usr/bin/env python3
"""Compile Authorize.Net's XSD sequences to a runtime ordering table. No runtime XML/network.

Run from the app directory: python3 scripts/generate-schema.py
The checked-in XSD was downloaded 2026-11-05 from:
https://api.authorize.net/xml/v1/schema/AnetApiSchema.xsd
"""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'schemas/AnetApiSchema.xsd'
NS = '{http://www.w3.org/2001/XMLSchema}'
root = ET.parse(SOURCE).getroot()
complex_types = {e.attrib['name']: e for e in root.findall(NS + 'complexType')}
simple_types = {e.attrib['name']: e for e in root.findall(NS + 'simpleType')}
elements = {e.attrib['name']: e for e in root.findall(NS + 'element')}
shapes = {}
scalars = {}

def local(s):
    return s.split(':')[-1]

def scalar(node):
    restriction = node.find(NS + 'restriction')
    if restriction is None:
        raise ValueError('Unsupported simple type')
    base = local(restriction.attrib['base'])
    if base in simple_types:
        spec = scalar(simple_types[base]).copy()
    else:
        spec = {'kind': 'boolean' if base == 'boolean' else 'number' if base in ('int', 'integer', 'long', 'short', 'unsignedByte', 'unsignedShort', 'unsignedInt', 'unsignedLong') else 'decimal' if base == 'decimal' else 'string'}
    choices = [e.attrib['value'] for e in restriction.findall(NS + 'enumeration')]
    if choices:
        spec['values'] = choices
    return spec

def type_of(node, path):
    name = node.get('type')
    if name:
        name = local(name)
        if name in complex_types:
            compile_shape(name, complex_types[name])
        elif name in simple_types:
            scalars[name] = scalar(simple_types[name])
        else:
            scalars[name] = {'kind': 'boolean' if name == 'boolean' else 'number' if name in ('int', 'integer', 'long', 'short', 'unsignedByte', 'unsignedShort', 'unsignedInt', 'unsignedLong') else 'decimal' if name == 'decimal' else 'string'}
        return name
    node_type = node.find(NS + 'complexType')
    if node_type is not None:
        compile_shape(path, node_type)
    else:
        simple = node.find(NS + 'simpleType')
        if simple is None:
            # The vendor leaves these EMV leaf values untyped; accept scalar text only.
            if node.get('name') not in ('emvData', 'emvDescriptor', 'emvVersion'):
                raise ValueError('Untyped element: ' + path)
            scalars[path] = {'kind': 'string'}
        else:
            scalars[path] = scalar(simple)
    return path

def compile_shape(name, node):
    if name in shapes:
        return
    shape = {'fields': [], 'choices': []}
    shapes[name] = shape
    def walk(parent, in_choice=False):
        for child in parent:
            tag = child.tag.removeprefix(NS)
            if tag in ('annotation',):
                continue
            if tag == 'extension':
                base = local(child.attrib['base'])
                compile_shape(base, complex_types[base])
                shape['fields'].extend(shapes[base]['fields'])
                shape['choices'].extend(shapes[base].get('choices', []))
                walk(child, in_choice)
            elif tag in ('sequence', 'complexContent'):
                walk(child, in_choice)
            elif tag == 'choice':
                # All reachable choices have direct element alternatives. Fail on new constructs.
                if any(x.tag not in (NS+'element', NS+'annotation') for x in child):
                    raise ValueError('Unsupported nested choice in ' + name)
                keys = [x.attrib['name'] for x in child if x.tag == NS+'element']
                shape['choices'].append(keys)
                walk(child, True)
            elif tag == 'element':
                key = child.attrib['name']
                field = {'key': key, 'type': type_of(child, name + '.' + key)}
                if child.get('maxOccurs', '1') != '1':
                    field['repeat'] = True
                if not in_choice and child.get('minOccurs', '1') != '0':
                    field['required'] = True
                shape['fields'].append(field)
            else:
                raise ValueError(f'Unsupported {tag} in {name}')
    walk(node)
    if not shape['choices']:
        del shape['choices']

requests = json.loads((ROOT / 'schemas/requests.json').read_text())
for request in requests:
    compile_shape(request, elements[request].find(NS+'complexType'))
header = '''// Generated by scripts/generate-schema.py from the pinned Authorize.Net XSD.
// Do not sort fields alphabetically: each array preserves xs:sequence and base-type order.
export interface WireField { key: string; type: string; repeat?: boolean; required?: boolean; }
export interface WireShape { fields: WireField[]; choices?: string[][]; }
export interface WireScalar { kind: "string" | "boolean" | "number" | "decimal"; values?: string[]; }
'''
output = header + 'export const SCHEMA_SHA256 = ' + json.dumps(hashlib.sha256(SOURCE.read_bytes()).hexdigest()) + ';\n'
output += 'export const REQUESTS: readonly string[] = ' + json.dumps(requests, indent=2) + ';\n'
output += 'export const SHAPES: Record<string, WireShape> = ' + json.dumps(shapes, indent=2) + ';\n'
output += 'export const SCALARS: Record<string, WireScalar> = ' + json.dumps(scalars, indent=2) + ';\n'
(ROOT / 'lib/schema.ts').write_text(output)
print(f'Generated {len(requests)} requests, {len(shapes)} object shapes, {len(scalars)} scalar types')
