/**
 * Shared request-building for the three sending endpoints (basic, templated, bulk).
 * Field names and limits are the vendor's (Email API > Send Basic Email / Appendix).
 */
export interface EmailObject {
  address: string;
  display_name?: string;
}

/**
 * Recipients arrive as a comma / semicolon / newline separated string (`a@x.com, Jane <j@x.com>`),
 * an array of such strings, or already-shaped `{ address, display_name }` objects.
 * A display name that itself contains a comma cannot be written in the string form: pass the
 * object form (a `json` value) for that.
 */
export function parseRecipients(value: unknown, name: string): EmailObject[] {
  const items: unknown[] = Array.isArray(value)
    ? value
    : typeof value === "string"
    ? value.split(/[;,\n]+/)
    : value && typeof value === "object"
    ? [value]
    : [];
  const out: EmailObject[] = [];
  for (const item of items) {
    if (item && typeof item === "object") {
      const o = item as { address?: unknown; display_name?: unknown };
      const address = String(o.address ?? "").trim();
      if (!address) throw new Error(`${name}: an entry has no address`);
      out.push(compact({ address, display_name: o.display_name as string | undefined }) as never);
      continue;
    }
    const s = String(item ?? "").trim();
    if (!s) continue;
    const m = s.match(/^(.*?)<\s*([^<>\s]+)\s*>$/);
    if (m) {
      const display = m[1].trim().replace(/^"|"$/g, "");
      out.push(compact({ address: m[2], display_name: display }) as never);
    } else {
      out.push({ address: s });
    }
  }
  return out;
}

export function requireRecipients(value: unknown, name: string): EmailObject[] {
  const list = parseRecipients(value, name);
  if (!list.length) throw new Error(`${name} is required`);
  return list;
}

/** An object-valued input given as an object or a JSON string. */
export function asObject(value: unknown, name: string): Record<string, unknown> | undefined {
  if (value === undefined || value === null || value === "") return undefined;
  const v = typeof value === "string" ? JSON.parse(value) : value;
  if (!v || typeof v !== "object" || Array.isArray(v)) {
    throw new Error(`${name} must be a JSON object`);
  }
  return v as Record<string, unknown>;
}

export function asArray(value: unknown, name: string): unknown[] | undefined {
  if (value === undefined || value === null || value === "") return undefined;
  const v = typeof value === "string" ? JSON.parse(value) : value;
  if (!Array.isArray(v)) throw new Error(`${name} must be a JSON array`);
  return v;
}

export function fromObject(address: unknown, name: unknown): EmailObject {
  return compact({
    address: need(address, "fromAddress"),
    display_name: name ? String(name).trim() : undefined,
  }) as unknown as EmailObject;
}

export function checkSubject(subject: unknown): string {
  const s = need(subject, "subject");
  if (s.length > 255) throw new Error("subject must not exceed 255 characters");
  return s;
}

const HEX24 = /^[0-9a-f]{24}$/i;

export function checkReferenceId(value: unknown): string | undefined {
  const v = String(value ?? "").trim();
  if (!v) return undefined;
  if (!HEX24.test(v)) throw new Error("referenceId must be a 24-character hexadecimal string");
  return v;
}

