export interface CommonInput {
  fromAddress: string;
  fromName?: string;
  to: unknown;
  cc?: unknown;
  bcc?: unknown;
  replyTo?: unknown;
  subject: string;
  tracking?: boolean;
  tags?: unknown;
  headers?: unknown;
  attachments?: unknown;
  scheduledAt?: string;
  referenceId?: string;
}

/** The members shared by `/emails` and `/emails/template`. */
export function commonBody(input: CommonInput): Record<string, unknown> {
  const total = [input.to, input.cc, input.bcc].reduce<number>(
    (n, v) => n + parseRecipients(v, "recipients").length,
    0,
  );
  if (total > 500) throw new Error("to, cc and bcc together may hold at most 500 recipients");
  const cc = parseRecipients(input.cc, "cc");
  const bcc = parseRecipients(input.bcc, "bcc");
  const replyTo = parseRecipients(input.replyTo, "replyTo");
  return compact({
    from: fromObject(input.fromAddress, input.fromName),
    to: requireRecipients(input.to, "to"),
    cc: cc.length ? cc : undefined,
    bcc: bcc.length ? bcc : undefined,
    reply_to: replyTo.length ? replyTo : undefined,
    subject: checkSubject(input.subject),
    tracking: typeof input.tracking === "boolean" ? input.tracking : undefined,
    tags: asObject(input.tags, "tags"),
    headers: asObject(input.headers, "headers"),
    attachments: asArray(input.attachments, "attachments"),
    scheduled_at: input.scheduledAt ? String(input.scheduledAt).trim() : undefined,
    reference_id: checkReferenceId(input.referenceId),
  });
}
