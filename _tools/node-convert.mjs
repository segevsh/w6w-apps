function convertApp(appDir) {
  const report = { path: appDir, tests: 0, leftovers: [], touched: 0, notes: [] };
  const abs = resolve(PACK, appDir);
  const pkgPath = join(abs, "package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const files = walk(abs).filter((f) => f.endsWith(".ts"));
  const assertPath = join(abs, "tests", "_assert.ts");
  const denoPath = join(abs, "tests", "_deno.ts");
  const generated = new Set([assertPath, denoPath]);

  const usedAssert = new Set();
  const usedDeno = new Set();
  const testFiles = [];
  let needsRegister = false;

  for (const f of files) {
    if (generated.has(f)) continue;
    const rel = relative(abs, f).split(sep).join("/");
    const original = readFileSync(f, "utf8");
    let src = original;
    const isTests = rel.startsWith("tests/");

    // value imports of @w6w/types|runtime need a runtime resolver under `node --test`
    if (/^import\s+(?!type\b)[^;]*?from\s+"@w6w\/(types|runtime)"/m.test(src)) needsRegister = true;

    // --- @std/assert
    src = src.replace(IMPORT_ASSERT, (_m, list) => {
      for (const raw of list.split(",").map((s) => s.trim()).filter(Boolean)) {
        const name = raw.replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
        if (!ASSERT_FNS[name] || ASSERT_FNS[name].internal) {
          report.leftovers.push(`${rel}: unsupported @std/assert export ${name}`);
          usedAssert.add("assert");
        } else usedAssert.add(name);
      }
      return `import {${list}} from "${relImport(f, assertPath).replace(/\.ts$/, ".ts")}";`;
    });

    // --- Deno.test
    const hasDenoTest = /\bDeno\.test\(/.test(src);
    if (hasDenoTest) {
      // alias the import when the file already has its own `test` binding (e.g. a helper)
      const clash = /\b(?:const|let|var|function|class)\s+test\b|[(,]\s*test\s*[,:)=]|\btest\s*=>/
        .test(src.replace(/\bDeno\.test\(/g, ""));
      const tn = clash ? "nodeTest" : "test";
      src = src.replace(/\bDeno\.test\(/g, tn + "(");
      src = insertImports(src, [
        clash ? `import { test as nodeTest } from "node:test";` : `import { test } from "node:test";`,
      ]);
      testFiles.push(rel);
    } else if (isTestFile(rel) && /from "node:test"/.test(src)) testFiles.push(rel);

    // --- Deno fs
    const denoUsed = new Set();
    for (const [from, to] of DENO_REWRITES) {
      const re = new RegExp(from.replace(".", "\\.") + "(?![A-Za-z])", "g");
      if (re.test(src)) {
        src = src.replace(re, to);
        denoUsed.add(to);
      }
    }
    if (denoUsed.size) {
      for (const d of denoUsed) usedDeno.add(d);
      src = insertImports(src, [
        `import { ${[...denoUsed].sort().join(", ")} } from "${relImport(f, denoPath)}";`,
      ]);
    }

    // --- @std/encoding in tests
    if (/@std\/encoding/.test(src) && isTests) {
      const conv = convertEncodingImports(src);
      if (conv) src = conv;
    }

    if (src !== original) {
      writeFileSync(f, src);
      report.touched++;
    }

    // leftovers: anything Deno / jsr / npm / @std still in the file after conversion
    const stripped = src.replace(/\/\*[\s\S]*?\*\/|(^|[^:])\/\/.*$/gm, "$1");
    for (const m of stripped.matchAll(/\bDeno\.\w+|"@std\/[\w/-]+"|"jsr:[^"]+"|"npm:[^"]+"/g)) {
      const tag = `${isTests ? "test" : "SOURCE"} ${rel}: ${m[0]}`;
      if (!report.leftovers.includes(tag)) report.leftovers.push(tag);
    }
  }

  // test files that were already node:test (idempotent re-run / hand converted) still count
  for (const f of files) {
    const rel = relative(abs, f).split(sep).join("/");
    if (isTestFile(rel) && !testFiles.includes(rel)) testFiles.push(rel);
  }
  report.tests = testFiles.length;

  if (usedAssert.size) writeIfChanged(assertPath, renderAssert(usedAssert));
  if (usedDeno.size) writeIfChanged(denoPath, renderDeno(usedDeno));

  // --- resolver hook
  const registerPath = join(abs, "tests", "_register.mjs");
  if (needsRegister) {
    const core = relative(
      join(abs, "tests"),
      resolve(PACK, "..", "core", "packages"),
    ).split(sep).join("/");
    writeIfChanged(registerPath, renderRegister(core));
    report.notes.push("register");
  }

  // --- package.json
  const entry = (pkg.w6w?.entry ?? "./index.ts").replace(/^\.\//, "");
  const dirs = new Map();
  for (const t of testFiles) {
    const m = t.match(/^(.*)\/[^/]*?(\.test|_test)\.ts$/) ?? ["", "", ""];
    const top = t.includes("/") ? t.split("/")[0] : ".";
    const kind = t.endsWith(".test.ts") ? ".test.ts" : "_test.ts";
    const key = top === "." ? t : `${top}/**/*${kind}`;
    dirs.set(key, true);
    void m;
  }
  const globs = [...dirs.keys()].sort();
  const testScript = globs.length
    ? `node --test --experimental-transform-types --no-warnings${
      needsRegister ? " --import ./tests/_register.mjs" : ""
    } ${globs.map((g) => `"${g}"`).join(" ")}`
    : `node -e ""`;
  // esbuild's tsconfig `paths` can't resolve a directory target (and 3 apps have no tsconfig),
  // so a value import of @w6w/types is aliased straight to its mod.ts.
  const typesMod = relative(abs, resolve(PACK, "..", "core", "packages", "types", "mod.ts"))
    .split(sep).join("/");
  const alias = needsRegister ? ` --alias:@w6w/types=${typesMod}` : "";
  const buildScript =
    `esbuild ${entry} --bundle --format=esm --platform=neutral --target=es2022 --minify${alias} --outfile=dist/app.js`;

  const next = { ...pkg, type: "module", main: "./dist/app.js" };
  next.scripts = { ...(pkg.scripts ?? {}), test: testScript, build: buildScript };
  delete next.devDependencies?.esbuild;
  if (next.devDependencies && !Object.keys(next.devDependencies).length) delete next.devDependencies;
  // key order: existing keys first, then type / main / scripts (as in the 2chat reference)
  const ordered = {};
  for (const k of Object.keys(pkg)) if (k in next) ordered[k] = next[k];
  for (const k of ["type", "main", "scripts"]) ordered[k] = next[k];
  const text = JSON.stringify(ordered, null, 2) + "\n";
  if (text !== readFileSync(pkgPath, "utf8")) writeFileSync(pkgPath, text);
  return report;
}

function writeIfChanged(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path) && readFileSync(path, "utf8") === text) return;
  writeFileSync(path, text);
}

function renderRegister(coreRel) {
  return `// Generated by _tools/node-convert.mjs. Do not edit by hand.
// Stands in for the tsconfig \`paths\` that Deno/esbuild use: under \`node --test\`
// \`@w6w/types\` and \`@w6w/runtime\` resolve to the sibling core checkout.
import { registerHooks } from "node:module";

const core = new URL("${coreRel}/", import.meta.url);
const map = {
  "@w6w/types": new URL("types/mod.ts", core).href,
  "@w6w/runtime": new URL("runtime/mod.ts", core).href,
};

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (map[specifier]) return { url: map[specifier], shortCircuit: true };
    return nextResolve(specifier, context);
  },
});
`;
}

