function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === "node_modules" || e.name === "dist" || e.name === ".git") continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function relImport(fromFile, toFile) {
  let r = relative(dirname(fromFile), toFile).split(sep).join("/");
  if (!r.startsWith(".")) r = "./" + r;
  return r;
}

const IMPORT_ASSERT = /import\s*\{([^}]*)\}\s*from\s*"@std\/assert"\s*;?/g;
const isTestFile = (f) => /\.test\.ts$|_test\.ts$/.test(f);

/** Base64 helpers used by tests, mapped onto Buffer. Returns null if it can't. */
const ENCODING_SHIMS = {
  encodeBase64: `((d: string | ArrayBuffer | Uint8Array) => typeof d === "string" ? Buffer.from(d, "utf8").toString("base64") : Buffer.from(d instanceof ArrayBuffer ? new Uint8Array(d) : d).toString("base64"))`,
  decodeBase64: `((s: string) => new Uint8Array(Buffer.from(s, "base64")))`,
  encodeBase64Url: `((d: string | ArrayBuffer | Uint8Array) => typeof d === "string" ? Buffer.from(d, "utf8").toString("base64url") : Buffer.from(d instanceof ArrayBuffer ? new Uint8Array(d) : d).toString("base64url"))`,
  decodeBase64Url: `((s: string) => new Uint8Array(Buffer.from(s, "base64url")))`,
  encodeHex: `((d: string | ArrayBuffer | Uint8Array) => typeof d === "string" ? Buffer.from(d, "utf8").toString("hex") : Buffer.from(d instanceof ArrayBuffer ? new Uint8Array(d) : d).toString("hex"))`,
  decodeHex: `((s: string) => new Uint8Array(Buffer.from(s, "hex")))`,
};

function convertEncodingImports(src) {
  let ok = true;
  const out = src.replace(
    /import\s*\{([^}]*)\}\s*from\s*"@std\/encoding(?:\/(base64url|base64|hex))?"\s*;?/g,
    (_m, list) => {
      const decls = [];
      for (const raw of list.split(",").map((s) => s.trim()).filter(Boolean)) {
        const m = raw.match(/^(\w+)(?:\s+as\s+(\w+))?$/);
        if (!m || !ENCODING_SHIMS[m[1]]) {
          ok = false;
          return _m;
        }
        decls.push(`const ${m[2] ?? m[1]} = ${ENCODING_SHIMS[m[1]]};`);
      }
      return decls.join("\n");
    },
  );
  return ok ? out : null;
}

/** First line index where an `import` statement starts, or 0. */
function insertImports(src, lines) {
  const m = src.match(/^import\b/m);
  const at = m ? m.index : 0;
  return src.slice(0, at) + lines.join("\n") + "\n" + src.slice(at);
}

