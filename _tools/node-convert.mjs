function renderDeno(names) {
  const n = new Set(names);
  const needsInfo = n.has("denoStat") || n.has("denoStatSync");
  const needsDir = n.has("denoReadDir") || n.has("denoReadDirSync");
  const promises = ["readFile", "stat", "readdir"].filter((f) =>
    (f === "readFile" && (n.has("denoReadTextFile") || n.has("denoReadFile"))) ||
    (f === "stat" && n.has("denoStat")) || (f === "readdir" && n.has("denoReadDir"))
  );
  const sync = ["readFileSync", "statSync", "readdirSync"].filter((f) =>
    (f === "readFileSync" && n.has("denoReadTextFileSync")) ||
    (f === "statSync" && n.has("denoStatSync")) || (f === "readdirSync" && n.has("denoReadDirSync"))
  );
  let out = `/**
 * Generated by _tools/node-convert.mjs: the \`Deno.*\` file-system calls this app's tests use,
 * on \`node:fs\`. Do not edit by hand; re-run the codemod instead.
 */
`;
  if (promises.length) out += `import { ${promises.join(", ")} } from "node:fs/promises";\n`;
  if (sync.length) {
    out += `import { ${sync.join(", ")} } from "node:fs";\n`;
  }
  if (needsDir) out += `import type { Dirent } from "node:fs";\n`;
  if (needsInfo) out += `import type { Stats } from "node:fs";\n`;
  out += "\n";
  if (needsInfo) {
    out += `export interface DenoFileInfo {
  isFile: boolean;
  isDirectory: boolean;
  isSymlink: boolean;
  size: number;
  mtime: Date;
}

function toInfo(s: Stats): DenoFileInfo {
  return {
    isFile: s.isFile(),
    isDirectory: s.isDirectory(),
    isSymlink: s.isSymbolicLink(),
    size: s.size,
    mtime: s.mtime,
  };
}

`;
  }
  if (needsDir) {
    out += `export interface DenoDirEntry {
  name: string;
  isFile: boolean;
  isDirectory: boolean;
  isSymlink: boolean;
}

function toEntry(e: Dirent): DenoDirEntry {
  return {
    name: e.name,
    isFile: e.isFile(),
    isDirectory: e.isDirectory(),
    isSymlink: e.isSymbolicLink(),
  };
}

`;
  }
  out += [...n].sort().map((k) => DENO_FNS[k]).join("\n\n") + "\n";
  return out;
}

