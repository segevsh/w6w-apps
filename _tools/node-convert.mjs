function renderAssert(names) {
  const order = [];
  const visit = (n) => {
    if (order.includes(n)) return;
    for (const d of ASSERT_FNS[n].deps) visit(d);
    order.push(n);
  };
  [...names].sort().forEach(visit);
  return ASSERT_HEADER + "\n" + order.map((n) => ASSERT_FNS[n].src).join("\n\n") + "\n";
}

