#!/usr/bin/env node
/**
 * Deno -> Node codemod for the apps pack. Plain Node, zero dependencies, idempotent.
 *
 *   node _tools/node-convert.mjs --all              # every app in w6w-pack.json
 *   node _tools/node-convert.mjs apps/2chat apps/google/gmail
 *   node _tools/node-convert.mjs --all --report out.json
 *
 * Per app it
 *  - adds `type: module`, `main: ./dist/app.js` and `scripts.test` / `scripts.build` to package.json
 *    (one shared esbuild lives in the pack root's node_modules; `npm run` finds it on PATH),
 *  - rewrites every Deno test file to `node:test`:
 *      `Deno.test(` -> `test(`,  `@std/assert` -> a generated per-app `tests/_assert.ts`,
 *      `Deno.readTextFile` & friends -> a generated per-app `tests/_deno.ts`,
 *      `@std/encoding` in tests -> Buffer,
 *  - writes `tests/_register.mjs` when sources value-import `@w6w/types` / `@w6w/runtime`
 *    (a `module.registerHooks` resolver standing in for the tsconfig `paths`).
 * Anything it cannot convert mechanically is listed in the report ("leftovers").
 */
